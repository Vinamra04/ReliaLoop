"""Generate `docs/slo-design.md` from the SLO specs and alerting profiles."""

from __future__ import annotations

from tools.slo.generator import budget_window, format_number, profile_for
from tools.slo.models import AvailabilitySli, SloSpec
from tools.slo.profiles import PROFILES, Profile, duration_seconds

HEADER = """<!-- GENERATED by `python -m tools.cli slo generate`. Do not edit by hand. -->
# SLO design

SLOs are defined as code in `slo/*.yaml`. `python -m tools.cli slo generate`
turns each spec into Prometheus recording rules and multi-window,
multi-burn-rate alerts (`observability/prometheus/rules/generated/`) and
regenerates this document. CI fails if the generated files are stale.

## How to read this

- **SLI** (indicator): the share of *good* events. For availability a good
  event is a non-5xx response; for latency it is a response faster than the
  threshold. Health, metrics and chaos routes never count.
- **SLO** (objective): the target for the SLI over a window, e.g. 99.5%.
- **Error budget**: what the objective leaves over, e.g. 0.5% of requests may
  fail. Spending it is normal; spending it too fast is an incident.
- **Burn rate**: how fast the budget is being spent. Burn rate 1 spends
  exactly the whole budget over the window; burn rate 14.4 spends it 14.4
  times faster.
- **Multi-window alerts**: an alert fires only when the burn rate is above
  its factor over *both* a long window (the problem is significant) and a
  short window (the problem is still happening). This is the method from the
  Google SRE Workbook, chapter "Alerting on SLOs".
- **No-traffic guard**: alerts also require a minimum request rate, so a
  single failed request at 3 a.m. cannot page anyone.
"""


def _sli_text(spec: SloSpec) -> str:
    if isinstance(spec.sli, AvailabilitySli):
        return "non-5xx responses / all responses"
    return f"responses within {format_number(spec.sli.threshold_seconds * 1000)} ms / all responses"


def _slo_table(specs: list[SloSpec]) -> str:
    lines = [
        "| SLO | Service | SLI | Objective | Error budget | Production window | Profile in use |",
        "|---|---|---|---|---|---|---|",
    ]
    lines.extend(
        f"| `{spec.name}` | {spec.service} | {_sli_text(spec)} | "
        f"{format_number(spec.objective)}% | {format_number(spec.error_budget * 100)}% | "
        f"{spec.window} | {spec.alerting.profile} |"
        for spec in specs
    )
    return "\n".join(lines)


def _budget_consumed(factor: float, long_window: str, budget_window_text: str) -> str:
    share = factor * duration_seconds(long_window) / duration_seconds(budget_window_text)
    return f"{format_number(round(share * 100, 1))}%"


def _profile_table(profile: Profile, window: str) -> str:
    lines = [
        "| Alert | Burn factor | Long window | Short window | `for` | Severity | "
        "Budget spent when it fires |",
        "|---|---|---|---|---|---|---|",
    ]
    lines.extend(
        f"| `SLOBurnRate{tier.tier.capitalize()}` | {format_number(tier.factor)} | "
        f"{tier.long_window} | {tier.short_window} | {tier.for_duration} | {tier.severity} | "
        f"{_budget_consumed(tier.factor, tier.long_window, window)} |"
        for tier in profile.tiers
    )
    return "\n".join(lines)


def _threshold_table(specs: list[SloSpec]) -> str:
    profile = PROFILES["production"]
    header = " | ".join(f"{tier.tier} ({format_number(tier.factor)}x)" for tier in profile.tiers)
    lines = [f"| SLO | {header} |", "|---|" + "---|" * len(profile.tiers)]
    for spec in specs:
        cells = " | ".join(
            f"{format_number(tier.factor * spec.error_budget * 100)}%" for tier in profile.tiers
        )
        lines.append(f"| `{spec.name}` | {cells} |")
    return "\n".join(lines)


def _meaning_list() -> str:
    return "\n".join(
        f"- **{tier.tier}** ({tier.severity}): {tier.meaning}"
        for tier in PROFILES["production"].tiers
    )


def render_slo_design(specs: list[SloSpec]) -> str:
    """Full text of `docs/slo-design.md`."""
    production = PROFILES["production"]
    demo = PROFILES["demo"]
    production_window = specs[0].window
    demo_window = budget_window(specs[0], demo)
    in_use = sorted({profile_for(spec).name for spec in specs})
    parts = [
        HEADER,
        "## SLOs\n",
        _slo_table(specs),
        "\n## Alerting profiles\n",
        f"Profiles currently in use by the specs: **{', '.join(in_use)}**.\n",
        "### Production profile (Google SRE Workbook values)\n",
        f"Error budget window: {production_window}.\n",
        _profile_table(production, production_window),
        "\n### Demo profile\n",
        "Same burn factors, windows compressed about 30x so that an injected fault "
        "is detected in roughly a minute. The error budget is accounted over "
        f"{demo_window} instead of {production_window}, so a single demo incident can spend "
        "the whole budget; it recovers as the incident leaves the window. This profile "
        "exists for demonstrations and tests only.\n",
        _profile_table(demo, demo_window),
        "\n## What each alert means\n",
        _meaning_list(),
        "\n## Bad-event ratio that triggers each alert\n",
        "Burn factor multiplied by the error budget: the share of bad events that must be "
        "exceeded over both windows.\n",
        _threshold_table(specs),
        "\n## Generated series\n",
        "| Series | Meaning |",
        "|---|---|",
        "| `slo:sli_error:ratio_rate<window>` | Share of bad events over the window |",
        "| `slo:sli_total:rate<window>` | Valid events per second over the window "
        "(no-traffic guard) |",
        "| `slo:burn_rate:ratio_<window>` | Bad-event ratio divided by the error budget |",
        "| `slo:error_budget_remaining:ratio` | 1 minus the burn rate over the budget window; "
        "1 = untouched, 0 = spent, negative = overspent |",
        "| `slo:objective:ratio` | The objective as a constant, for dashboards |",
        "\nAll series carry the labels `slo` and `service`.\n",
    ]
    return "\n".join(parts)
